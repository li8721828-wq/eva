import { execFile, spawn } from 'node:child_process'
import fs from 'node:fs/promises'
import path from 'node:path'
import { redactSensitiveText } from '../memory-sanitizer'

export async function findHostExecutable(launcher: string): Promise<string> {
  for (const directory of (process.env.PATH ?? '').split(path.delimiter)) {
    if (!path.isAbsolute(directory)) continue
    const candidate = path.join(directory, launcher)
    if (process.platform === 'win32' && /["%!^&|<>\r\n]/.test(candidate)) continue
    if (await fs.stat(candidate).then((stat) => stat.isFile(), () => false)) return candidate
  }
  throw new Error(`PATH 中找不到 ${launcher}，请配置宿主工具后重试。`)
}

export function mavenDiagnostic(output: string, phase: string): string {
  const lines = output.replace(/\x1b\[[0-9;]*m/g, '').split(/\r?\n/)
  const missing = [...output.matchAll(/(?:artifacts could not be resolved|Could not find artifact):?\s*([^\r\n]+)/gi)]
    .flatMap(([, message]) => message.match(/[\w.-]+:[\w.-]+:[\w.-]+(?::[\w.-]+){1,2}/g) ?? [])
  if (missing.length) return `缺少 Maven 依赖 ${[...new Set(missing)].join('、')}`
  const useful = lines.filter((line) => /\[ERROR\]\s*\S/.test(line) && !/\[Help \d+\] https?:|To see the full|Re-run Maven|For more information/.test(line))
  const reason = (useful.length ? useful : lines.filter(Boolean)).slice(0, 5)
    .map((line) => redactSensitiveText(line.replace(/https?:\/\/[^\s)]+/g, '[仓库地址]'), 620)).join('\n')
  return [`Maven ${phase} 失败`, reason].filter(Boolean).join('\n')
}

/** Invoke only the PATH launcher and fixed Maven arguments, with bounded output and process-tree cancellation. */
export function runMaven(launcher: string, cwd: string, args: string[], phase: string, timeout: number, signal?: AbortSignal): Promise<string> {
  signal?.throwIfAborted()
  const windows = process.platform === 'win32'
  // Values are generated by the verifier or validated module/test identifiers. Never interpolate shell syntax.
  if (windows && args.some((arg) => !/^[\w./,=:-]+$/.test(arg))) throw new Error('Maven 参数含不支持的字符。')
  const systemDirectory = path.join(process.env.SystemRoot || 'C:\\Windows', 'System32')
  const executable = windows ? path.join(systemDirectory, 'cmd.exe') : launcher
  const argv = windows ? ['/d', '/s', '/v:off', '/c', `""${launcher}" ${args.map((arg) => `"${arg}"`).join(' ')}"`] : args
  return new Promise((resolve, reject) => {
    const child = spawn(executable, argv, {
      cwd, windowsHide: true, windowsVerbatimArguments: windows, detached: !windows, stdio: ['ignore', 'pipe', 'pipe'],
    })
    let output = ''
    let stopReason: Error | undefined
    let stopped: Promise<void> | undefined
    const stop = (reason: Error) => {
      if (stopReason) return
      stopReason = reason
      if (!child.pid) return
      if (windows) {
        stopped = new Promise((done) => {
          execFile(path.join(systemDirectory, 'taskkill.exe'), ['/pid', String(child.pid), '/t', '/f'], { windowsHide: true, timeout: 8000 }, (error) => {
            if (error) child.kill()
            done()
          })
        })
      } else {
        try { process.kill(-child.pid, 'SIGKILL') } catch { child.kill('SIGKILL') }
      }
    }
    const abort = () => stop(new Error('已取消宿主验证。'))
    const timer = setTimeout(() => stop(new Error(`Maven ${phase} 超时。`)), timeout)
    const collect = (chunk: string) => { output = (output + chunk).slice(-256 * 1024) }
    child.stdout.setEncoding('utf8').on('data', collect)
    child.stderr.setEncoding('utf8').on('data', collect)
    signal?.addEventListener('abort', abort, { once: true })
    if (signal?.aborted) abort()
    child.on('error', (error) => { stopReason ??= new Error(`无法启动 Maven ${phase}。${error.message}`) })
    child.once('close', async (code) => {
      clearTimeout(timer)
      signal?.removeEventListener('abort', abort)
      await stopped
      if (stopReason) reject(stopReason)
      else if (code === 0) resolve(output)
      else reject(new Error(mavenDiagnostic(output, phase)))
    })
  })
}
